#!/usr/bin/env python3
"""Writes the parameter tables that the plugin, the Pico and the web page compile, from parameters.json.
Each build runs it, so the tables can't go stale; they stay committed, so
a change to the list shows what it does to each. `--check` only reports whether they're up to date (exit 1
if not), for the checks.

parameters.json lists every parameter once, in the order hosts list them. Each has
  key       permanent: what the plugin's saved state and patches use
  id, enum  the CLAP id (0, 1, 2 … with no gaps; fixed once in use) and its C name
  name      what hosts and the page show
  unit      UNIT_SECONDS, UNIT_PERCENT (0 to 1), UNIT_NUMBER, UNIT_CENTS, UNIT_HERTZ, or a unit in
            `choices`, which names its values (a switch)
  min, max, default   in real units
  stepped   whole values only
  curve, mid          the knob law: "log" if set, and the value at 12 o'clock (default: halfway, or the
                      geometric middle for log)
  section, slot, control, short   where the panel shows it (web/src/instrument.ts): the SH-101 section, its place
                      in it, "fader", "knob", "selector", "switch" or "button", and its printed label
  cc        the MIDI CC that sets it; the rest get free CCs in id order
`choices` names the values of the units that are lists.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / 'params/parameters.json'
HEADER = 'Generated by params/generate.py from params/parameters.json: change those, not this.'
# What the page calls each number unit (web/src/live.ts).
PANEL_UNITS = {'UNIT_PERCENT': '%', 'UNIT_HERTZ': 'Hz', 'UNIT_SECONDS': 's', 'UNIT_CENTS': 'cents'}
NUMBER_UNITS = ['UNIT_SECONDS', 'UNIT_PERCENT', 'UNIT_NUMBER', 'UNIT_CENTS', 'UNIT_HERTZ']
# CCs left alone: bank select, mod wheel, data entry, volume, pan, expression, pedals, (N)RPN, channel
# mode. The rest go to parameters in id order.
FREE_CCS = [3, 9, *range(14, 32), *range(70, 80), *range(85, 91), *range(102, 120)]


def cpp_double(v):
    return repr(float(v))


def c_float(v):
    return repr(float(v)) + 'f'


def c_bool(v):
    return 'true' if v else 'false'


def load():
    source = json.loads(SOURCE.read_text())
    entries, choices = source['parameters'], source.get('choices', {})
    have = sorted(entries, key=lambda e: e['id'])
    for i, e in enumerate(have):
        if e['id'] != i:
            sys.exit(f"ids must run 0 to {len(have) - 1} with none missing; {e['key']} has {e['id']}")
    for what in ('key', 'enum'):
        names = [e[what] for e in entries]
        if len(set(names)) != len(names):
            sys.exit(f'Each {what} must appear once.')
    taken = {e['cc'] for e in entries if 'cc' in e}
    free = [cc for cc in FREE_CCS if cc not in taken]
    for e in have:
        if e['unit'] not in NUMBER_UNITS and e['unit'] not in choices:
            sys.exit(f"{e['key']}: unit {e['unit']} is neither a number unit nor in choices")
        if e.get('curve') == 'log' and e['min'] <= 0:
            sys.exit(f"{e['key']} is log, so its min must be above 0")
        if not e['min'] <= e['default'] <= e['max'] or e['min'] >= e['max']:
            sys.exit(f"{e['key']} needs min < max and its default between them")
        e.setdefault('cc', free.pop(0) if free else -1)
    return entries, choices


def plugin(entries):
    """synth/params.generated.h: the CLAP ids and the plugin's table, rows in the list's order."""
    out = [f'// {HEADER}', '// Included by params.h, after its struct Param.', '#pragma once', '',
           '// The CLAP ids. Hosts save automation and presets by id, so an id never',
           '// changes once a version is released: a new one goes at the end.',
           'enum ParamId {']
    out += [f"  {e['enum']}," for e in sorted(entries, key=lambda e: e['id'])]
    out += ['  P_COUNT              // Always present as last param to get count', '};', '',
            'inline constexpr Param paramTable[] = {']
    for e in entries:
        out.append(f"    {{{e['enum']}, \"{e['key']}\", \"{e['name']}\", {cpp_double(e['min'])}, {cpp_double(e['max'])}, "
                   f"{cpp_double(e['default'])}, {c_bool(e['stepped'])}, {e['unit']}}},")
    out += ['};', '']
    return '\n'.join(out)


def choice_names(choices):
    """synth/paramChoices.generated.h: every unit, and the named ones' names, for paramText.h."""
    out = [f'// {HEADER}', '// Included by paramText.h.', '#pragma once', '',
           '// A new unit with named values: an entry in parameters.json\'s choices.', 'enum ParamUnit {']
    out += [f'  {u},' for u in NUMBER_UNITS + list(choices)]
    out += ['};', '']
    for unit, names in choices.items():
        quoted = ', '.join(json.dumps(name, ensure_ascii=False) for name in names)
        out.append(f'inline const char *const {unit.lower()}_names[] = {{{quoted}}};')
    out += ['', '// A stepped unit\'s choices, in their values\' order, and how many; nullptr for a number unit.',
            'inline const char *const *ParamChoices(ParamUnit unit, int *count) {', '  switch (unit) {']
    for unit, names in choices.items():
        out.append(f'  case {unit}:\n    return *count = {len(names)}, {unit.lower()}_names;')
    out += ['  default:', '    return *count = 0, nullptr;', '  }', '}', '']
    return '\n'.join(out)


def web(entries, choices):
    """web/src/params.generated.ts: the same list for the GUI page (the Pico's, the plugin's, the app's)."""
    keep = ('key', 'id', 'enum', 'name', 'unit', 'min', 'max', 'default', 'stepped', 'curve', 'mid',
            'section', 'slot', 'control', 'short', 'cc')
    rows = []
    for e in sorted(entries, key=lambda e: e['id']):
        row = {k: e[k] for k in keep if k in e}
        row['log'] = e.get('curve') == 'log'
        row['mid'] = e.get('mid', (e['min'] * e['max']) ** 0.5 if row['log'] else (e['min'] + e['max']) / 2)
        if e['unit'] in choices:
            row['choices'] = choices[e['unit']]
        rows.append(row)
    return (f'// {HEADER}\n'
            'export interface Parameter {\n'
            '  key: string; id: number; enum: string; name: string; unit: string;\n'
            '  min: number; max: number; default: number; stepped: boolean; log: boolean; mid: number;\n'
            '  curve?: string; section: string; slot: number; control: string; short: string;\n'
            '  cc?: number; choices?: string[];\n'
            '}\n'
            f'export const parameters: Parameter[] = {json.dumps(rows, indent=1, ensure_ascii=False)};\n'
            f'export const choices: Record<string, string[]> = {json.dumps(choices, indent=1, ensure_ascii=False)};\n'
            f'export const panelUnits: Record<string, string> = {json.dumps(PANEL_UNITS, indent=1)};\n')


def pico(entries):
    """firmware/paramKnobs.generated.h: the knob law and CCs, for turning MIDI and the page into values."""
    rows = []
    for e in sorted(entries, key=lambda e: e['id']):
        log = e.get('curve') == 'log'
        mid = e.get('mid', (e['min'] * e['max']) ** 0.5 if log else (e['min'] + e['max']) / 2)
        rows.append(f"    {{{c_float(e['min'])}, {c_float(mid)}, {c_float(e['max'])}, {c_float(e['default'])}, "
                    f"{c_bool(log)}, {c_bool(e['stepped'])}, {e['cc']}}}, // {e['enum']}")
    rows = '\n'.join(rows)
    return f"""// {HEADER}
// The Pico's view of the parameters: how a knob position (MIDI CC, 0 to 1) becomes a value, and which CC
// sets which. Ids are the plugin's (synth/params.generated.h).
#pragma once
#include <cmath>
#include <cstdint>

namespace params
{{
struct Info
{{
    float min, mid, max, initial; // mid: the value at the knob's centre
    bool log;                     // logarithmic knob
    bool stepped;                 // whole values only
    int8_t cc;                    // MIDI CC that sets it, -1 for none
}};

inline constexpr Info table[] = {{
{rows}
}};

inline constexpr int count = sizeof table / sizeof table[0];

// The exponent that puts mid at the centre of a log knob.
inline float logShape(const Info& p)
{{
    return std::log(std::log(p.mid / p.min) / std::log(p.max / p.min)) / std::log(0.5f);
}}

// Knob position 0 to 1 to the value in the list's units.
inline float toValue(int id, float position)
{{
    const Info& p = table[id];
    float x = position < 0.0f ? 0.0f : position > 1.0f ? 1.0f : position;
    float v = p.log ? p.min * std::pow(p.max / p.min, std::pow(x, logShape(p)))
            : x < 0.5f ? p.min + (p.mid - p.min) * x * 2 : p.mid + (p.max - p.mid) * (x - 0.5f) * 2;
    return p.stepped ? std::round(v) : v;
}}

inline float toPosition(int id, float value)
{{
    const Info& p = table[id];
    float v = value < p.min ? p.min : value > p.max ? p.max : value;
    if (p.log) return std::pow(std::log(v / p.min) / std::log(p.max / p.min), 1 / logShape(p));
    if (v < p.mid) return p.mid > p.min ? (v - p.min) / (p.mid - p.min) / 2 : 0;
    return p.max > p.mid ? 0.5f + (v - p.mid) / (p.max - p.mid) / 2 : 1;
}}

inline int fromCc(uint8_t cc)
{{
    for (int id = 0; id < count; ++id)
        if (table[id].cc == cc) return id;
    return -1;
}}
}} // namespace params
"""


def outputs(entries, choices):
    return {
        ROOT / 'synth/params.generated.h': plugin(entries),
        ROOT / 'synth/paramChoices.generated.h': choice_names(choices),
        ROOT / 'web/src/params.generated.ts': web(entries, choices),
        ROOT / 'firmware/paramKnobs.generated.h': pico(entries),
    }


def main():
    entries, choices = load()
    stale = []
    for path, text in outputs(entries, choices).items():
        if not path.exists() or path.read_text() != text:
            stale.append(path)
            if '--check' not in sys.argv:
                path.write_text(text)
    if '--check' in sys.argv:
        if stale:
            sys.exit('Out of date; run params/generate.py: ' + ', '.join(str(p.relative_to(ROOT)) for p in stale))
        print('Parameter tables up to date.')


if __name__ == '__main__':
    main()
