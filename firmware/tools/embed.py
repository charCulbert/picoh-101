#!/usr/bin/env python3
"""Puts the web page into a C++ header, so the firmware can serve it from flash.
Starts at index.html and follows what it loads (link and script tags, JS imports,
CSS url()), so only the files the page uses go in, at their paths under web/.

The page is one block, webPage, which the app downloads whole (GET /page, or over USB MIDI):
a line "<size> <type> <path>" per file, an empty line, then the files one after another.
webPageHash is its FNV-1a 64 hash; webFiles points into it, for serving the files one by one.

usage: embed.py out.h web/ [served-path=file ...]   (extra files, such as generated ones)
       embed.py --list web/ [served-path=file ...]  (print the files, for CMake's DEPENDS)
"""
import os
import re
import sys

TYPES = {".html": "text/html", ".js": "text/javascript", ".css": "text/css", ".svg": "image/svg+xml",
         ".woff2": "font/woff2", ".json": "application/json"}
REFERENCES = {
    ".html": [r'(?:href|src)="([^"#?]+)"'],
    ".js": [r'(?:^|\n)\s*import\s+(?:[^"\']*?\s+from\s+)?["\']([^"\']+)["\']'],
    ".css": [r'url\(\s*["\']?([^"\')]+)["\']?\s*\)'],
}


def collect(root, extra):
    found, queue = {}, ["index.html"]
    while queue:
        served = queue.pop()
        if served in found:
            continue
        path = extra.get(served, os.path.join(root, served))
        if not os.path.exists(path):
            sys.exit(f"embed.py: {served} is referenced but missing ({path})")
        found[served] = path
        text = open(path, "rb").read().decode("utf-8", "replace")
        for pattern in REFERENCES.get(os.path.splitext(served)[1], []):
            for ref in re.findall(pattern, text):
                if re.match(r"^[a-z]+:", ref) or ref.startswith("/"):
                    continue
                queue.append(os.path.normpath(os.path.join(os.path.dirname(served), ref)))
    return found


def fnv1a64(data):
    h = 0xcbf29ce484222325
    for b in data:
        h = ((h ^ b) * 0x100000001b3) & 0xffffffffffffffff
    return h


def main():
    args = sys.argv[1:]
    listing = args[0] == "--list"
    if listing:
        args = args[1:]
    out = None if listing else args.pop(0)
    root = args.pop(0)
    extra = dict(a.split("=", 1) for a in args)
    files = collect(root, extra)
    if listing:
        print(";".join(sorted(files.values())))
        return
    files = sorted(files.items())
    datas = [open(path, "rb").read() for _, path in files]
    kinds = [TYPES.get(os.path.splitext(served)[1], "application/octet-stream") for served, _ in files]
    header = "".join(f"{len(d)} {k} {served}\n" for (served, _), d, k in zip(files, datas, kinds)) + "\n"
    page = header.encode() + b"".join(datas)
    entries, at = [], len(header)
    for (served, _), data, kind in zip(files, datas, kinds):
        entries.append(f'    {{"/{served}", "{kind}", webPage + {at}, {len(data)}}},')
        at += len(data)
    lines = ["// Generated by tools/embed.py. Do not edit.", "#pragma once", "#include <cstdint>", "",
             "struct WebFile { const char* path; const char* type; const uint8_t* data; uint32_t size; };", "",
             f"inline constexpr uint8_t webPage[] = {{{','.join(str(b) for b in page)}}};",
             f"inline constexpr uint32_t webPageSize = {len(page)};",
             f"inline constexpr uint64_t webPageHash = 0x{fnv1a64(page):016x}ull;", "",
             "inline constexpr WebFile webFiles[] = {", *entries, "};", ""]
    with open(out, "w") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    main()
